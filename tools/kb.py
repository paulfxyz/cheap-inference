#!/usr/bin/env python3
"""
kb.py - deterministic tooling for an LLM-maintained markdown knowledge base.

The model WRITES pages. This script CHECKS them. Checking in code instead of
asking a model to "review its own work" matters for two reasons:

  1. COST   - a lint pass over 1,000 pages takes milliseconds and 0 tokens.
  2. TRUST  - a model reviewing its own output tends to agree with itself;
              a script has no such bias and cannot be talked out of a rule.

LAYOUT (relative to the folder this script is run against, --root)
------------------------------------------------------------------
  raw/                 source material. Humans add files, the model never edits.
  wiki/                pages written and maintained by the model.
  wiki/index.md        one line per page (generated by `index`).
  wiki/hot.md          a short "what matters right now" cache (hand/model kept).
  .brain/manifest.json which raw file was ingested, at which hash, into which pages.

COMMANDS
--------
  status              list raw files that are NEW, CHANGED or DELETED since ingest.
  done RAW PAGE...    record that RAW was ingested into the given wiki pages.
  lint [--skip-stale] run every rule below; exit code 2 if anything fails. Use --skip-stale
                      between writing pages and `done`; run a strict lint after `done`.
  index               regenerate wiki/index.md.
  stats               sizes, token estimates, page ages, biggest pages.
  stale [--days N]    pages not updated for N days (default 90).

LINT RULES
----------
  R1  every page has frontmatter with: title, sources, updated
  R2  every source listed in frontmatter exists under raw/
  R3  every [[wiki link]] resolves to a page
  R4  no orphan pages (every page has at least one inbound link)
  R5  no TODO / FIXME left behind
  R6  every quoted claim  > "text" - raw/file  appears word-for-word in that file
  R7  raw files changed after ingest are flagged, with the pages now stale
  R8  hot.md stays small (default <= 25 lines): a cache that grows is not a cache
  R9  a page larger than --max-page-tokens is flagged: split it so a query can
      open just the part it needs
  R10 the `updated` date is a valid YYYY-MM-DD and not in the future

What the linter CANNOT do: judge whether a source is TRUE. A wrong source makes
a faithfully wrong wiki. Keep a human in the loop for what goes into raw/.

Standard library only. Python 3.10+.
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import pathlib
import re
import sys

# ------------------------------------------------------------------ patterns
# [[page]], [[page|alias]] and [[page#heading]] all link to "page".
LINK = re.compile(r"\[\[([^\]|#]+)(?:[#|][^\]]*)?\]\]")
# A "quote line":  > "exact words" - raw/some-file.md   (hyphen or long dashes allowed)
QUOTE = re.compile(r'^>\s*"(.+?)"\s*[\u2014\u2013-]+\s*(raw/\S+)\s*$', re.M)
# Pages that are infrastructure, exempt from content rules.
SPECIAL = {"index.md", "hot.md", "log.md"}


# ------------------------------------------------------------------- helpers
def sha(path: pathlib.Path) -> str:
    """Short content hash. 16 hex chars is plenty to detect edits."""
    return hashlib.sha256(path.read_bytes()).hexdigest()[:16]


def tokens_of(text: str) -> int:
    """Cheap token estimate (chars/4). Good enough to rank and to set limits."""
    return round(len(text) / 4)


def normalise(s: str) -> str:
    """Collapse whitespace so line-wrapping differences never cause false alarms."""
    # Typographic quotes and dashes are mapped to ASCII so a curly quote never causes a false
    # "QUOTE NOT IN SOURCE" (review finding: verbatim matching was brittle to punctuation).
    table = {ord(c): "'" for c in "\u2018\u2019"} | {ord(c): '"' for c in "\u201c\u201d"} | {ord(c): "-" for c in "\u2013\u2014"}
    return " ".join(s.translate(table).split())


def parse_frontmatter(text: str):
    """Parse a minimal `---` YAML block of `key: value` lines. Returns dict or None.

    We avoid a YAML dependency on purpose: the rules only need flat keys.
    """
    if not text.startswith("---\n"):
        return None
    end = text.find("\n---", 4)
    if end < 0:
        return None
    fm = {}
    for line in text[4:end].splitlines():
        if ":" in line:
            key, value = line.split(":", 1)
            fm[key.strip()] = value.strip()
    return fm


class KB:
    """A knowledge base rooted at a folder. Holds paths and offers the operations."""

    def __init__(self, root: pathlib.Path, max_page_tokens: int = 1500, hot_max_lines: int = 25):
        self.root = root.resolve()
        self.raw = self.root / "raw"
        self.wiki = self.root / "wiki"
        self.manifest_path = self.root / ".brain" / "manifest.json"
        self.max_page_tokens = max_page_tokens
        self.hot_max_lines = hot_max_lines

    # -- file discovery -----------------------------------------------------
    def raw_files(self):
        return sorted(p for p in self.raw.rglob("*") if p.is_file()) if self.raw.exists() else []

    def pages(self):
        return sorted(self.wiki.rglob("*.md")) if self.wiki.exists() else []

    def rel(self, p: pathlib.Path) -> str:
        return str(p.relative_to(self.root))

    # -- manifest -------------------------------------------------------------
    def load_manifest(self) -> dict:
        if self.manifest_path.exists():
            return json.loads(self.manifest_path.read_text(encoding="utf-8"))
        return {}

    def save_manifest(self, m: dict) -> None:
        self.manifest_path.parent.mkdir(parents=True, exist_ok=True)
        # sort_keys => stable diffs in git, so a re-ingest shows only real changes.
        self.manifest_path.write_text(json.dumps(m, indent=2, sort_keys=True), encoding="utf-8")

    # ---------------------------------------------------------------- status
    def status(self) -> list[tuple[str, str]]:
        """Return [(NEW|CHANGED|DELETED, raw_path)]. This is the incremental ingest work-list.

        Cost follows THIS list, not the size of the vault: unchanged files are
        never re-read by the model.
        """
        m = self.load_manifest()
        todo = []
        for p in self.raw_files():
            k = self.rel(p)
            if k not in m:
                todo.append(("NEW", k))
            elif m[k]["sha"] != sha(p):
                todo.append(("CHANGED", k))
        for k in m:
            if not (self.root / k).exists():
                todo.append(("DELETED", k))
        return todo

    # ------------------------------------------------------------------ done
    def done(self, raw: str, pages: list[str]) -> int:
        """Record that `raw` was ingested into `pages` (all paths relative to root)."""
        rp = self.root / raw
        if not rp.exists():
            print(f"no such raw file: {raw}")
            return 1
        for w in pages:
            if not (self.root / w).exists():
                print(f"no such page: {w}")
                return 1
        m = self.load_manifest()
        m[raw] = {"sha": sha(rp), "pages": pages, "ingested": dt.date.today().isoformat()}
        self.save_manifest(m)
        return 0

    # ------------------------------------------------------------------ lint
    def lint(self, today: dt.date | None = None, skip_stale: bool = False) -> list[str]:
        """Run every rule and return a list of human-readable problems (empty = clean)."""
        today = today or dt.date.today()
        errs: list[str] = []
        texts = {p: p.read_text(encoding="utf-8") for p in self.pages()}
        names = {p.stem: p for p in texts}
        inbound = {n: 0 for n in names}
        manifest = self.load_manifest()

        for p, t in texts.items():
            r = self.rel(p)

            # R8: the hot cache must stay small.
            if p.name == "hot.md":
                lines = len([ln for ln in t.splitlines() if ln.strip()])
                if lines > self.hot_max_lines:
                    errs.append(f"{r}: hot cache has {lines} non-empty lines (max {self.hot_max_lines})")

            # Links are counted for ALL pages (index links to everything, which is fine).
            for link in LINK.findall(t):
                if link in names:
                    if names[link] != p:  # a self-link must not rescue an orphan
                        inbound[link] += 1
                else:
                    errs.append(f"{r}: broken link [[{link}]]")

            if p.name in SPECIAL:
                continue

            # R1: frontmatter
            fm = parse_frontmatter(t)
            if fm is None:
                errs.append(f"{r}: missing frontmatter")
                continue
            for need in ("title", "sources", "updated"):
                if need not in fm:
                    errs.append(f"{r}: frontmatter lacks '{need}'")

            # R2: sources exist
            for src in re.findall(r"raw/[^\s,\]\[]+", fm.get("sources", "")):
                if not (self.root / src).exists():
                    errs.append(f"{r}: source {src} does not exist")

            # R10: date sanity
            if "updated" in fm:
                try:
                    d = dt.date.fromisoformat(fm["updated"])
                    if d > today:
                        errs.append(f"{r}: updated date {fm['updated']} is in the future")
                except ValueError:
                    errs.append(f"{r}: updated '{fm['updated']}' is not YYYY-MM-DD")

            # R5: leftovers
            if re.search(r"\b(TODO|FIXME)\b", t):
                errs.append(f"{r}: unresolved TODO/FIXME")

            # R6: quotes must exist verbatim in the cited raw file
            for quote, src in QUOTE.findall(t):
                f = self.root / src
                if not f.exists():
                    errs.append(f"{r}: quote cites missing {src}")
                elif normalise(quote) not in normalise(f.read_text(encoding="utf-8", errors="ignore")):
                    errs.append(f'{r}: QUOTE NOT IN SOURCE -> "{quote[:60]}" ({src})')

            # R9: page size
            if tokens_of(t) > self.max_page_tokens:
                errs.append(f"{r}: ~{tokens_of(t)} tokens exceeds {self.max_page_tokens}; split it")

        # R4: orphans (content pages only)
        for n, c in inbound.items():
            if c == 0 and names[n].name not in SPECIAL:
                errs.append(f"{self.rel(names[n])}: orphan (no inbound links)")

        # R7: raw changed after ingest. During an ingest the manifest is updated by `done` AFTER the
        # pages are written, so a correct edit would keep failing R7 until `done` runs (a sequencing bug
        # found in review). `lint --skip-stale` runs every rule except R7 for that mid-ingest pass;
        # run a strict `lint` after `done`.
        for k, v in ({} if skip_stale else manifest).items():
            f = self.root / k
            if f.exists() and sha(f) != v["sha"]:
                errs.append(f"{k}: changed since ingest, pages stale: {', '.join(v['pages'])}")
        return errs

    # ----------------------------------------------------------------- index
    def build_index(self) -> int:
        """Write wiki/index.md: one line per page. This is Tier 1 of tiered loading."""
        rows = []
        for p in self.pages():
            if p.name in SPECIAL:
                continue
            fm = parse_frontmatter(p.read_text(encoding="utf-8")) or {}
            rows.append(f"- [[{p.stem}]] - {fm.get('title', p.stem)} ({fm.get('updated', '?')})")
        (self.wiki / "index.md").write_text("# Index\n\n" + "\n".join(rows) + "\n", encoding="utf-8")
        return len(rows)

    # ----------------------------------------------------------------- stats
    def stats(self) -> dict:
        pages = [(self.rel(p), tokens_of(p.read_text(encoding="utf-8"))) for p in self.pages()]
        total = sum(t for _, t in pages)
        return {
            "raw_files": len(self.raw_files()),
            "pages": len(pages),
            "total_tokens": total,
            "biggest": sorted(pages, key=lambda x: -x[1])[:5],
            # Rough guide: below ~50-100 sources, plain search beats a wiki.
            "dead_zone": len(self.raw_files()) < 50,
        }

    # ----------------------------------------------------------------- stale
    def stale(self, days: int = 90, today: dt.date | None = None) -> list[tuple[str, int]]:
        """Pages whose `updated` date is older than `days`. The lifecycle check
        that a plain wiki lacks: nothing else tells you a page has gone old."""
        today = today or dt.date.today()
        out = []
        for p in self.pages():
            if p.name in SPECIAL:
                continue
            fm = parse_frontmatter(p.read_text(encoding="utf-8")) or {}
            try:
                age = (today - dt.date.fromisoformat(fm.get("updated", ""))).days
            except ValueError:
                continue  # missing/invalid dates are reported by lint, not here
            if age > days:
                out.append((self.rel(p), age))
        return sorted(out, key=lambda x: -x[1])


# ----------------------------------------------------------------------- CLI
def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", default=".", help="knowledge-base folder (default: current)")
    ap.add_argument("--max-page-tokens", type=int, default=1500)
    ap.add_argument("--hot-max-lines", type=int, default=25)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("status")
    d = sub.add_parser("done"); d.add_argument("raw"); d.add_argument("pages", nargs="+")
    lp = sub.add_parser("lint"); lp.add_argument("--skip-stale", action="store_true", help="skip R7 (use between writing pages and running `done`)")
    sub.add_parser("index")
    sub.add_parser("stats")
    s = sub.add_parser("stale"); s.add_argument("--days", type=int, default=90)
    a = ap.parse_args(argv)

    kb = KB(pathlib.Path(a.root), a.max_page_tokens, a.hot_max_lines)
    if a.cmd == "status":
        todo = kb.status()
        for kind, k in todo:
            print(kind, k)
        print(f"pending: {len(todo)}", file=sys.stderr)
        return 0
    if a.cmd == "done":
        return kb.done(a.raw, a.pages)
    if a.cmd == "lint":
        errs = kb.lint(skip_stale=a.skip_stale)
        for e in errs:
            print(e, file=sys.stderr)
        print(f"lint: {len(errs)} problem(s) in {len(kb.pages())} pages", file=sys.stderr)
        return 2 if errs else 0  # exit 2 is what a Claude-style PostToolUse hook feeds back to the model
    if a.cmd == "index":
        print(f"index: {kb.build_index()} pages")
        return 0
    if a.cmd == "stats":
        print(json.dumps(kb.stats(), indent=2))
        return 0
    if a.cmd == "stale":
        for path, age in kb.stale(a.days):
            print(f"{age:>5} days  {path}")
        return 0
    return 1


if __name__ == "__main__":
    sys.exit(main())
